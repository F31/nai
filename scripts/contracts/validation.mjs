import { readFile } from 'node:fs/promises';
import Ajv2020 from 'ajv/dist/2020.js';
import SwaggerParser from '@apidevtools/swagger-parser';
import { operationErrors, OPENAPI_DOCUMENTS } from './openapi-ops.mjs';

export const readJson = async filename => JSON.parse(await readFile(filename, 'utf8'));

/// Every JSON Schema this repository validates against, keyed by the name the
/// tests use. It is exported so that "which schemas are consumed" is a single
/// readable list — the guard in `tests/contracts/schema.test.mjs` derives the
/// consumed set from it instead of keeping a second list that would go stale
/// (ADR 0051 decision 3).
///
/// `registry` is the *production* data file rather than a fixture: it lives in
/// `tests/registry.yaml` and is parsed as YAML, so its validator is exercised by
/// `tests/registry.test.mjs`, not by the JSON fixture loop below.
export const AJV_SOURCES = {runtime:'config/runtime',provider:'config/provider',backup:'config/backup',binding:'config/binding-plan',avatar2d:'config/avatar-2d',plugin:'plugin/manifest',model:'plugin/model',catalog:'catalog/catalog',avatar:'plugin/avatar',ui:'plugin/ui',platforms:'platform-matrix/platforms',registry:'tests/registry'};

/// The subset of `AJV_SOURCES` that has a TypeScript counterpart generated by
/// `scripts/contracts/generate.mjs`. Keeping it here — rather than as a second
/// array inside the generator — is what makes "generated into TypeScript but
/// never validated" impossible to state, let alone to ship (ADR 0052 decision 4).
/// Every source listed here MUST also be in `AJV_SOURCES`; the guard in
/// `tests/contracts/schema.test.mjs` asserts that, plus a two-way match against
/// the checked-in generated directory.
export const TS_GENERATED_SOURCES = ['catalog/catalog','config/runtime','config/provider','config/backup','config/binding-plan','config/avatar-2d','plugin/manifest','plugin/model','plugin/avatar','plugin/ui'];

export async function validators() {
  const ajv = new Ajv2020({ allErrors: true, strict: true, strictRequired: false });
  return Object.fromEntries(await Promise.all(Object.entries(AJV_SOURCES).map(async ([key, source]) => [key, ajv.compile(await readJson(`schemas/${source}.schema.json`))])));
}

export function validateSemantic(kind, value) {
  if (kind === 'runtime') {
    if (value.media.lease_expire_ms <= value.media.lease_renew_ms) throw new Error('lease expiry must exceed renewal interval');
    if (value.media.startup_buffer_ms > value.media.max_buffer_ms) throw new Error('startup buffer exceeds maximum');
    if (BigInt(value.budgets.per_session_limit_minor) > 18446744073709551615n) throw new Error('budget amount exceeds uint64');
  }
  if (kind === 'model') {
    const ids = new Set(value.graphs.map(graph => graph.id));
    if (ids.size !== value.graphs.length || value.required_graph_ids.some(id => !ids.has(id))) throw new Error('model graph closure is incomplete or duplicated');
  }
  if (kind === 'provider') {
    const endpoint = new URL(value.endpoint);
    if (endpoint.username || endpoint.password || [...endpoint.searchParams.keys()].some(key => /token|secret|api.?key/i.test(key))) throw new Error('endpoint must not contain credentials');
  }
  if (kind === 'catalog') {
    const ids = new Set(value.capabilities.map(capability => capability.id));
    const frozen = new Set(value.capabilities.filter(capability => capability.stage === 'frozen').map(capability => capability.id));
    // Legacy adapters point at what has been frozen: a draft has no frozen wire
    // representation to adapt to yet, so "target is in the catalog" is too weak.
    if (ids.size !== value.capabilities.length || value.adapters_required.some(adapter => !frozen.has(adapter.target))) throw new Error('duplicate capability or unresolved adapter target');
    // Mirrors the JSON Schema: a half-declared draft would make the stage field
    // unreadable, which is the one thing the field exists to prevent.
    if (value.capabilities.some(capability => capability.stage === 'draft' && ['request','response','stream','session_scoped'].some(key => capability[key] !== undefined))) throw new Error('draft capability declares consumer messages');
  }
}

/// 仓库里**每一份** OpenAPI 描述都过同一道判据。文档集来自 `OPENAPI_DOCUMENTS`（逐文档声明，
/// 逐字写死），而不是这里硬编码的一条路径——W85 修好了「哪些**操作**被校验」，这一层是
/// 「哪些**文档**被校验」，同族洞的第七处（W86 / ADR 0064）。
///
/// 每份文档两件事：① 顶层 `x-implementation-status` MUST 等于该文档声明的期望值；
/// ② 操作集 MUST 闭合（权限声明、状态的声明一致性、path-item 键集闭世界、声明无孤儿、非空洞）。
/// 判据本身在 `openapi-ops.mjs` 里（纯函数、与 I/O 分离），这里只负责把它接到文档上。
export async function apiDocuments() {
  const documents = {};
  for (const [docPath, declaration] of Object.entries(OPENAPI_DOCUMENTS)) {
    const document = await SwaggerParser.validate(docPath);
    if (document['x-implementation-status'] !== declaration.status) {
      throw new Error(
        `${docPath} must preserve implementation status ${JSON.stringify(declaration.status)}`,
      );
    }
    const errors = operationErrors(document, declaration.implemented);
    if (errors.length > 0) throw new Error(`${docPath} operation set is not closed:\n${errors.join('\n')}`);
    documents[docPath] = document;
  }
  return documents;
}

/// 控制面 API 描述（`schemas/openapi/control.yaml`）——`apiDocuments()` 的一份视图。
export async function apiDocument() {
  return (await apiDocuments())['schemas/openapi/control.yaml'];
}
