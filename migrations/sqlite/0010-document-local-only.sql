-- W131: 文档级「不外发」标记（V3.11 §13.2「local_only 数据不上传」、§281「标记 local_only 的
-- 文档只走本地词法检索或人工」、INV-17「数据外发范围……受 local_only 约束」）。
--
-- 为什么是**独立的列**而不是复用 `acl_ref` 或 `product_scope`：那是两个不同的事实
-- （访问控制引用、产品域）。把 `local_only` 塞进其中任何一个，就是让一格记两件事——
-- 读的人无法分辨手里那个值说的是哪一种。同一件事 MUST NOT 两处定义，两个不同的事
-- MUST NOT 挤进同一个字段。
--
-- 为什么 `NOT NULL DEFAULT 0`，而不是可空三态：`local_only` 是一个**二值事实**
-- （是 / 否），没有「未知」这一格。导入入口 `ImportedDocument.local_only` 是**必填**的，
-- 所以每一条新写入都必须表态；可空会把「未标记」与「不知道」混为一谈，而后者在这里
-- 不存在。
--
-- ⚠️ 老行（升级前导入）在该列上读到 `0`，它的含义是「**从未被标记**」——是升级时点的
-- 历史事实，**不是**「已核实这份文档可以外发」。后者是一个没有人做过的核对，MUST NOT
-- 被写成前者的同义词。这一点写在这里、写在 `version_ten_upgrade_...` 用例里、也写在
-- 轮次报告里。
--
-- 为什么不改 `0001-foundation.sql`：`verify()` 逐文件核对已应用迁移的 SHA-256，
-- 改 0001 会让每一个既有库的校验和漂移。这与 0008 / 0009 是同一个理由。
ALTER TABLE documents ADD COLUMN local_only INTEGER NOT NULL DEFAULT 0;
